    /**
     * Inserts a new bank account into PostgreSQL.
     *
     * @param account the account being saved
     * @return the account ID generated by PostgreSQL
     * @throws SQLException if the database operation fails
     */
    public long insertAccount(Account account) throws SQLException {
        //Own the transaction so the customer lock stays held through the insert.
        try (Connection connection = connectionProvider.getConnection()) {
            boolean originalAutoCommit = connection.getAutoCommit();
            try {
                connection.setAutoCommit(false);
                long accountId = insertAccount(connection, account);
                connection.commit();
                return accountId;
            } catch (SQLException | RuntimeException exception) {
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }
                throw exception;
            } finally {
                connection.setAutoCommit(originalAutoCommit);
            }
        }
    }

    /**
     * Retrieves all accounts belonging to a customer.
     *
     * @param customer the customer whose accounts should be retrieved
     * @return a list of the customer's accounts
     * @throws SQLException if the database query fails
     */
    public List<Account> findAccountsByCustomer(Customer customer) throws SQLException {
        if (customer == null || customer.getId() <= 0) {
            throw new IllegalArgumentException("A valid customer is required.");
        }

        //Join all the account related tables together and get all accounts for a customer
        String sqlQuery = """
        SELECT
            a.account_id, a.account_number, a.account_type, a.balance, a.status,
            i.principal AS investment_principal, i.term_months AS investment_term_months,
            i.interest_rate AS investment_interest_rate, i.withdrawal_unlocked_date,
            l.principal_amount AS loan_principal, l.annual_interest_rate,
            l.repayment_period_in_months, l.loan_start_date
        FROM accounts a
        LEFT JOIN investment_details i ON a.account_id = i.account_id
        LEFT JOIN loan_details l ON a.account_id = l.account_id
        WHERE a.customer_id = ?
        ORDER BY a.account_id
        """;


        List<Account> accounts = new ArrayList<>();

        //Retrieve only accounts belonging to this customer.
        try (Connection connection = connectionProvider.getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {

            preparedStatement.setLong(1, customer.getId());

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                while (resultSet.next()) {
                    String accountType = resultSet.getString("account_type");
                    Account account;

                    switch (accountType) {
                        case "CHECKING":
                            //Create a Checking Account using its existing constructor.
                            account = new CheckingAccount(customer);
                            break;

                        case "SAVINGS":
                            //Use the bank's fixed 3.75% annual Savings Account interest rate.
                            account = new SavingsAccount(customer, new BigDecimal("3.75"));
                            break;

                        case "INVESTMENT":
                            //Read the Investment Account details saved in PostgreSQL.
                            BigDecimal investmentPrincipal = resultSet.getBigDecimal("investment_principal");
                            int investmentTermMonths = resultSet.getInt("investment_term_months");
                            BigDecimal investmentInterestRate = resultSet.getBigDecimal("investment_interest_rate");
                            Date withdrawalUnlockedDate = resultSet.getDate("withdrawal_unlocked_date");

                            //Reject an Investment Account that is missing its required details.
                            if (investmentPrincipal == null || investmentInterestRate == null ||
                                    withdrawalUnlockedDate == null || investmentTermMonths <= 0) {
                                throw new SQLException("Investment Account is missing required details.");
                            }

                            account = new InvestmentAccount(customer, investmentPrincipal,
                                    investmentTermMonths, investmentInterestRate,
                                    withdrawalUnlockedDate.toLocalDate());
                            break;

                        case "LOAN":
                            //Read the Loan Account details saved in PostgreSQL.
                            BigDecimal loanPrincipal = resultSet.getBigDecimal("loan_principal");
                            BigDecimal annualInterestRate = resultSet.getBigDecimal("annual_interest_rate");
                            int repaymentPeriodInMonths = resultSet.getInt("repayment_period_in_months");
                            Date loanStartDate = resultSet.getDate("loan_start_date");

                            //Reject a Loan Account that is missing its required details.
                            if (loanPrincipal == null || annualInterestRate == null ||
                                    loanStartDate == null || repaymentPeriodInMonths <= 0) {
                                throw new SQLException("Loan Account is missing required details.");
                            }

                            account = new LoanAccount(customer, loanPrincipal, annualInterestRate,
                                    repaymentPeriodInMonths, loanStartDate.toLocalDate());
                            break;

                        default:
                            //Reject account types that the application does not recognize.
                            throw new SQLException("Unsupported account type: " + accountType);
                    }


                    //Restore the saved account information.
                    account.setId(resultSet.getLong("account_id"));
                    account.setAccountNumber(resultSet.getString("account_number"));
                    account.setBalance(resultSet.getBigDecimal("balance"));
                    account.setStatus(resultSet.getString("status"));

                    accounts.add(account);
                }
            }
        }

        return accounts;
    }


    /**
     * Inserts a new bank account using an existing database connection.
     * Allows the caller to include the insert in a larger transaction.
     *
     * @param connection the database connection used for the transaction
     * @param account the account being saved
     * @return the account ID generated by PostgreSQL
     * @throws SQLException if the database operation fails
     */
    public long insertAccount(Connection connection, Account account) throws SQLException {
        if (connection == null || account == null || account.getAccountOwnerName() == null
                || account.getAccountOwnerName().getId() <= 0) {
            throw new IllegalArgumentException("A connection and account with a valid owner are required.");
        }

        //Lock the customer first, using the same transaction as the account insert.
        //This coordinates with CustomerClosureDAO and checks current database status.
        String customerLockSql = "SELECT status FROM customers WHERE customer_id = ? FOR UPDATE";
        try (PreparedStatement customerLock = connection.prepareStatement(customerLockSql)) {
            customerLock.setLong(1, account.getAccountOwnerName().getId());
            try (ResultSet customerResult = customerLock.executeQuery()) {
                if (!customerResult.next() || !"ACTIVE".equals(customerResult.getString("status"))) {
                    throw new IllegalStateException("Only active customers can open bank accounts.");
                }
            }
        }

        String sqlQuery = """
            INSERT INTO accounts (customer_id, account_type, balance, status)
            VALUES (?, ?, ?, ?)
            RETURNING account_id, account_number
            """;

        //Use the provided connection without opening or closing another one.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {

            //Set the account information.
            preparedStatement.setLong(1, account.getAccountOwnerName().getId());
            preparedStatement.setString(2, account.getAccountType());
            preparedStatement.setBigDecimal(3, account.getBalance());
            preparedStatement.setString(4, account.getStatus());

            //Insert the account and retrieve its generated information.
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (resultSet.next()) {
                    long accountId = resultSet.getLong("account_id");
                    String accountNumber = resultSet.getString("account_number");

                    //Reject invalid information returned by PostgreSQL.
                    if (accountId <= 0 || accountNumber == null || accountNumber.isBlank()) {
                        throw new SQLException("Account insertion returned invalid account information.");
                    }

                    account.setId(accountId);
                    account.setAccountNumber(accountNumber);
                    return accountId;
                }

                throw new SQLException("Account insertion did not return an account ID.");
            }
        }
    }


