    /**
     * Retrieves the current balance of an account belonging to a customer.
     *
     * @param accountId the database ID of the account
     * @param customerId the database ID of the account owner
     * @return the current account balance
     * @throws SQLException if the account cannot be found or the query fails
     */
    public BigDecimal getAccountBalance(long accountId, long customerId) throws SQLException {
        //Check that both database IDs are valid.
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }

        String sqlQuery = """
            SELECT balance
            FROM accounts
            WHERE account_id = ? AND customer_id = ?
            """;

        //Open a connection and retrieve the balance for the customer's account.
        try (Connection connection = connectionProvider.getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {

            preparedStatement.setLong(1, accountId);
            preparedStatement.setLong(2, customerId);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                //Reject accounts that do not exist or belong to another customer.
                if (!resultSet.next()) {
                    throw new SQLException("Account not found for this customer.");
                }

                return resultSet.getBigDecimal("balance");
            }
        }
    }



    /**
     * Deposits money into an active Checking or Savings Account.
     * Updates the balance atomically and returns the new balance.
     *
     * @param connection the connection managing the database transaction
     * @param accountId the database ID of the receiving account
     * @param customerId the database ID of the account owner
     * @param amount the amount to deposit
     * @return the updated account balance
     * @throws SQLException if the account cannot accept the deposit or the query fails
     */
    public BigDecimal deposit(Connection connection, long accountId, long customerId,
                              BigDecimal amount) throws SQLException {
        //Check that the account and customer IDs are valid.
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }

        //Check that the deposit amount is positive and has no more than two decimal places.
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("Deposit amount must be positive with no more than two decimal places.");
        }

        String sqlQuery = """
            UPDATE accounts
            SET balance = balance + ?,
                updated_at = CURRENT_TIMESTAMP
            WHERE account_id = ?
              AND customer_id = ?
              AND account_type IN ('CHECKING', 'SAVINGS')
              AND status = 'ACTIVE'
            RETURNING balance
            """;

        //Use the caller's connection so the deposit can be part of a transaction.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setBigDecimal(1, amount);
            preparedStatement.setLong(2, accountId);
            preparedStatement.setLong(3, customerId);

            //Update the account and retrieve its new balance.
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Account not found or not eligible for deposits.");
                }

                return resultSet.getBigDecimal("balance");
            }
        }
    }


    /**
     * Withdraws money from an active Checking or Savings Account with sufficient funds.
     * The database checks the balance and account ownership in one atomic update.
     *
     * @param connection the connection managing the database transaction
     * @param accountId the account's database ID
     * @param customerId the account owner's database ID
     * @param amount the amount to withdraw
     * @return the updated account balance
     * @throws SQLException if the withdrawal cannot be completed
     */
    public BigDecimal withdraw(Connection connection, long accountId, long customerId,
                               BigDecimal amount) throws SQLException {
        //Check that the IDs and withdrawal amount are valid.
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("Withdrawal amount must be positive with no more than two decimal places.");
        }

        String sqlQuery = """
            UPDATE accounts
            SET balance = balance - ?,
                updated_at = CURRENT_TIMESTAMP
            WHERE account_id = ?
              AND customer_id = ?
              AND account_type IN ('CHECKING', 'SAVINGS')
              AND status = 'ACTIVE'
              AND balance >= ?
            RETURNING balance
            """;

        //Use the caller's connection so the withdrawal stays in one transaction.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setBigDecimal(1, amount);
            preparedStatement.setLong(2, accountId);
            preparedStatement.setLong(3, customerId);
            preparedStatement.setBigDecimal(4, amount);

            //Reject missing, ineligible, or insufficiently funded accounts.
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Withdrawal rejected: insufficient funds or account not eligible.");
                }
                return resultSet.getBigDecimal("balance");
            }
        }
    }


