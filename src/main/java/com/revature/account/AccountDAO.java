    public List<InvestmentContribution> findInvestmentContributions(long accountId,
                                                                    long customerId) throws SQLException {
        //Reject invalid IDs before opening a database connection.
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }

        //Keep the existing standalone retrieval behavior for interest previews.
        try (Connection connection = connectionProvider.getConnection()) {
            return findInvestmentContributions(connection, accountId, customerId);
        }
    }

    /**
     * Retrieves investment contributions using the caller's transaction connection.
     * The caller can hold the Investment Account row lock while reading these records.
     * Does not commit, roll back, or close the provided connection.
     *
     * @param connection the connection managing the maturity payout
     * @param accountId the Investment Account database ID
     * @param customerId the owning customer database ID
     * @return contribution amounts and timestamps ordered by date and ID
     * @throws SQLException if the account is not owned by the customer or the query fails
     */
    public List<InvestmentContribution> findInvestmentContributions(Connection connection,
                                                                    long accountId,
                                                                    long customerId) throws SQLException {
        //Reject invalid inputs before accessing JDBC.
        if (connection == null || accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("A connection and valid account and customer IDs are required.");
        }

        String sqlQuery = """
                SELECT ic.amount, ic.contributed_at
                FROM accounts AS a
                LEFT JOIN investment_contributions AS ic ON ic.account_id = a.account_id
                WHERE a.account_id = ?
                  AND a.customer_id = ?
                  AND a.account_type = 'INVESTMENT'
                ORDER BY ic.contributed_at NULLS FIRST, ic.contribution_id
                """;

        List<InvestmentContribution> contributions = new ArrayList<>();

        //Close the statement and results, but leave the transaction connection open.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setLong(1, accountId);
            preparedStatement.setLong(2, customerId);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Investment Account not found for this customer.");
                }

                do {
                    //The LEFT JOIN produces one empty row for an unfunded account.
                    BigDecimal amount = resultSet.getBigDecimal("amount");
                    OffsetDateTime contributedAt = resultSet.getObject(
                            "contributed_at", OffsetDateTime.class);
                    if (amount == null && contributedAt == null) {
                        continue;
                    }
                    if (amount == null || contributedAt == null) {
                        throw new SQLException("Investment contribution record is incomplete.");
                    }
                    contributions.add(new InvestmentContribution(amount, contributedAt));
                } while (resultSet.next());
            }
        }

        return contributions;
    }


    /**
     * Closes a matured, active Investment Account and returns its contributed balance.
     * The caller must credit the destination and commit or roll back the same transaction.
     * PostgreSQL locks the source row and checks maturity and status atomically.
     *
     * @param connection the caller's transaction connection
     * @param accountId the Investment Account ID
     * @param customerId the owning customer ID
     * @return the contributed balance released before the account was zeroed
     * @throws SQLException if the account is ineligible or the database operation fails
     */
    public BigDecimal releaseMaturedInvestment(Connection connection, long accountId,
                                               long customerId) throws SQLException {
        //Reject invalid account ownership identifiers before querying PostgreSQL.
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }

        String sqlQuery = """
                WITH eligible AS MATERIALIZED (
                    SELECT a.account_id, a.balance
                    FROM accounts AS a
                    JOIN investment_details AS i ON i.account_id = a.account_id
                    WHERE a.account_id = ?
                      AND a.customer_id = ?
                      AND a.account_type = 'INVESTMENT'
                      AND a.status = 'ACTIVE'
                      AND CURRENT_DATE >= i.withdrawal_unlocked_date
                    FOR UPDATE OF a
                )
                UPDATE accounts AS a
                SET balance = 0.00,
                    status = 'CLOSED',
                    updated_at = CURRENT_TIMESTAMP
                FROM eligible
                WHERE a.account_id = eligible.account_id
                  AND a.status = 'ACTIVE'
                RETURNING eligible.balance AS released_balance
                """;

        //Leave transaction ownership with the caller; close only our JDBC resources.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setLong(1, accountId);
            preparedStatement.setLong(2, customerId);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Investment maturity release rejected: account not eligible.");
                }

                BigDecimal releasedBalance = resultSet.getBigDecimal("released_balance");
                if (releasedBalance == null || releasedBalance.signum() < 0) {
                    throw new SQLException("Investment maturity release returned an invalid balance.");
                }
                return releasedBalance;
            }
        }
    }

    /**
     * Credits principal and interest to an active Checking or Savings Account.
     * Must be called in the same transaction as the matured investment release.
     *
     * @param connection the caller's transaction connection
     * @param accountId the destination account ID
     * @param customerId the owning customer ID
     * @param amount the positive maturity payout amount
     * @return the updated destination balance
     * @throws SQLException if the destination is ineligible or the update fails
     */
    public BigDecimal creditInvestmentMaturityPayout(Connection connection, long accountId,
                                                     long customerId, BigDecimal amount) throws SQLException {
        //Require a valid destination and a positive amount with at most two decimal places.
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2 ||
                amount.setScale(2, java.math.RoundingMode.UNNECESSARY).precision() > 19) {
            throw new IllegalArgumentException("Maturity payout must be positive and have no more than two decimal places.");
        }

        String sqlQuery = """
                UPDATE accounts
                SET balance = balance + ?,
                    updated_at = CURRENT_TIMESTAMP
                WHERE account_id = ?
                  AND customer_id = ?
                  AND account_type IN ('CHECKING', 'SAVINGS')
                  AND status = 'ACTIVE'
                  AND balance + ? <= 99999999999999999.99
                RETURNING balance
                """;

        //Use the existing transaction connection without committing or closing it.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setBigDecimal(1, amount);
            preparedStatement.setLong(2, accountId);
            preparedStatement.setLong(3, customerId);
            preparedStatement.setBigDecimal(4, amount);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Investment maturity payout rejected: destination not eligible or balance limit exceeded.");
                }
                return resultSet.getBigDecimal("balance");
            }
        }
    }

    /**
     * Closes an owned, active Checking or Savings Account only when its balance is zero.
     * The conditional update prevents a concurrent deposit from racing with closure.
     * Existing transactions and account history are preserved.
     *
     * @param accountId the account to close
     * @param customerId the customer who owns the account
     * @throws SQLException if the account is ineligible or the database update fails
     */
    public void closeCheckingOrSavingsAccount(long accountId, long customerId) throws SQLException {
        if (accountId <= 0 || customerId <= 0) {
            throw new IllegalArgumentException("Valid account and customer IDs are required.");
        }

        String sqlQuery = """
                UPDATE accounts
                SET status = 'CLOSED',
                    updated_at = CURRENT_TIMESTAMP
                WHERE account_id = ?
                  AND customer_id = ?
                  AND account_type IN ('CHECKING', 'SAVINGS')
                  AND status = 'ACTIVE'
                  AND balance = 0.00
                RETURNING account_id
                """;

        //The update and eligibility checks execute atomically in PostgreSQL.
        try (Connection connection = connectionProvider.getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setLong(1, accountId);
            preparedStatement.setLong(2, customerId);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Account closure rejected: account must be owned, active, Checking or Savings, and have a zero balance.");
                }
            }
        }
    }

