
package com.revature.account;

import com.revature.customer.Customer;
import java.math.BigDecimal;

/**
 * Represents a customer's bank account
 * Stores the account ID, owner, and current balance.
 */
public abstract class Account {

    private long id;
    private final Customer accountOwner;
    private BigDecimal balance;
    private String accountNumber;
    private String status;

    /**
     * Creates a new bank account for a customer.
     * New accounts start with a zero balance and active status.
     *
     * @param accountOwner the customer who owns the account
     * @throws IllegalArgumentException if the account owner is null
     */
    public Account(Customer accountOwner) {
        //Make sure the account has a valid owner.
        if (accountOwner == null) {
            throw new IllegalArgumentException("Account owner cannot be null.");
        }

        this.accountOwner = accountOwner;
        this.balance = BigDecimal.ZERO.setScale(2);
        this.status = "ACTIVE";
    }


    /**
     * Sets the account ID generated by PostgreSQL.
     *
     * @param id the account ID
     */
    public void setId(long id) {
        this.id = id;
    }

    /**
     * Gets the account ID.
     *
     * @return the account ID
     */
    public long getId() {
        return id;
    }

    /**
     * Gets the customer who owns the account.
     *
     * @return the account owner
     */
    public Customer getAccountOwnerName() {
        return accountOwner;
    }

    /**
     * Gets the account owner's full name.
     *
     * @return the customer's full name
     */
    public String getAccountOwner() {
        return accountOwner.getCustomerFullName();
    }

    /**
     * Sets the account balance.
     *
     * @param balance the new account balance
     * @throws IllegalArgumentException if the balance is null or negative
     */
    public void setBalance(BigDecimal balance) {
        //Make sure the balance is not null or negative.
        if (balance == null || balance.signum() < 0) {
            throw new IllegalArgumentException("Account balance cannot be null or negative.");
        }

        //Store the balance with exactly two decimal places.
        this.balance = balance.setScale(2, java.math.RoundingMode.UNNECESSARY);
    }

    /**
     * Gets the current account balance.
     *
     * @return the account balance
     */
    public BigDecimal getBalance() {
        return balance;
    }


    /**
     * Gets the account number.
     *
     * @return the account number
     */
    public String getAccountNumber() {
        return accountNumber;
    }

    /**
     * Sets the account number.
     *
     * @param accountNumber the account number assigned to this account
     */
    public void setAccountNumber(String accountNumber) {
        this.accountNumber = accountNumber;
    }

    /**
     * Gets the account status.
     *
     * @return the account status
     */
    public String getStatus() {
        return status;
    }

    /**
     * Sets the account status.
     *
     * @param status the new account status
     */
    public void setStatus(String status) {
        this.status = status;
    }


    /**
     * Gets the account type used when storing this account in PostgreSQL.
     * Each account subclass provides its own type.
     *
     * @return the account type
     */
    public abstract String getAccountType();


}
