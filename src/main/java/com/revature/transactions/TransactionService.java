package com.revature.transactions;

import com.revature.account.Account;
import com.revature.account.AccountDAO;
import com.revature.account.investment.InvestmentAccount;
import com.revature.account.investment.InvestmentInterestService;
import com.revature.account.investment.InvestmentMaturityValidator;
import java.time.LocalDate;
import com.revature.customer.Customer;
import com.revature.util.ConnectionProvider;
import com.revature.util.DatabaseConnection;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;

/**
 * Handles financial transactions and coordinates their database operations.
 */
public class TransactionService {

    private final AccountDAO accountDAO;
    private final TransactionDAO transactionDAO;
    private final ConnectionProvider connectionProvider;

    /**
     * Creates a TransactionService using the actual PostgreSQL database.
     */
    public TransactionService() {
        this(new AccountDAO(), new TransactionDAO(), DatabaseConnection::getConnection);
    }

    /**
     * Creates a TransactionService with provided database dependencies.
     * Allows unit tests to use mocked DAOs and connections.
     *
     * @param accountDAO the DAO responsible for account database operations
     * @param transactionDAO the DAO responsible for transaction records
     * @param connectionProvider the provider of database connections
     */
    public TransactionService(AccountDAO accountDAO, TransactionDAO transactionDAO,
                              ConnectionProvider connectionProvider) {
        //Check that all required dependencies were provided.
        if (accountDAO == null || transactionDAO == null || connectionProvider == null) {
            throw new IllegalArgumentException("TransactionService dependencies cannot be null.");
        }

        this.accountDAO = accountDAO;
        this.transactionDAO = transactionDAO;
        this.connectionProvider = connectionProvider;
    }

    /**
     * Deposits money into an active Checking or Savings Account.
     * Updates the account balance, records the deposit, and saves its audit in one database transaction.
     *
     * @param customer the authenticated customer making the deposit
     * @param account the account receiving the deposit
     * @param amount the amount of money being deposited
     * @return the transaction ID generated by PostgreSQL
     * @throws SQLException if any database operation fails
     */
    public long deposit(Customer customer, Account account, BigDecimal amount) throws SQLException {
        //Check that the customer is active and has a valid database ID.
        if (customer == null || customer.getId() <= 0 || !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException("An active customer is required to make a deposit.");
        }

        //Check that the account has a valid database ID.
        if (account == null || account.getId() <= 0) {
            throw new IllegalArgumentException("A valid account is required to make a deposit.");
        }

        //Only Checking and Savings Accounts can receive regular deposits.
        if (!"CHECKING".equals(account.getAccountType()) &&
                !"SAVINGS".equals(account.getAccountType())) {
            throw new IllegalArgumentException("Deposits are only available for Checking and Savings Accounts.");
        }

        //Check that the selected account is active.
        if (!"ACTIVE".equals(account.getStatus())) {
            throw new IllegalStateException("Deposits are only available for active accounts.");
        }

        //Check that the amount is positive and has no more than two decimal places.
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("Deposit amount must be positive with no more than two decimal places.");
        }

        //Open one database connection for the balance update, transaction record, and audit.
        try (Connection connection = connectionProvider.getConnection()) {
            connection.setAutoCommit(false);

            try {
                //Update the balance using the authenticated customer's ID.
                BigDecimal updatedBalance = accountDAO.deposit(
                        connection, account.getId(), customer.getId(), amount);

                //Record the successful deposit using the same database connection.
                long transactionId = transactionDAO.insertDepositTransaction(
                        connection, account.getId(), amount, updatedBalance);

                //Record the successful deposit in the audit table using the same connection.
                transactionDAO.insertDepositAudit(connection, customer.getId(), transactionId);

                //Commit all three operations only after they succeed.
                connection.commit();

                return transactionId;
            } catch (SQLException | RuntimeException exception) {
                //Undo the balance update, transaction record, and audit if any operation fails.
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }

                throw exception;
            }
        }
    }

    /**
     * Withdraws money from an active Checking or Savings Account.
     * Updates the balance, records the withdrawal, and saves its audit atomically.
     *
     * @param customer the authenticated customer making the withdrawal
     * @param account the account being debited
     * @param amount the amount to withdraw
     * @return the transaction ID generated by PostgreSQL
     * @throws SQLException if any database operation fails
     */
    public long withdraw(Customer customer, Account account, BigDecimal amount) throws SQLException {
        //Check that the customer is active and has a valid database ID.
        if (customer == null || customer.getId() <= 0 || !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException("An active customer is required to make a withdrawal.");
        }

        //Check that the selected account is saved and eligible for withdrawals.
        if (account == null || account.getId() <= 0) {
            throw new IllegalArgumentException("A valid account is required to make a withdrawal.");
        }
        if (!"CHECKING".equals(account.getAccountType()) &&
                !"SAVINGS".equals(account.getAccountType())) {
            throw new IllegalArgumentException("Withdrawals are only available for Checking and Savings Accounts.");
        }
        if (!"ACTIVE".equals(account.getStatus())) {
            throw new IllegalStateException("Withdrawals are only available for active accounts.");
        }

        //Check that the amount is positive and has no more than two decimal places.
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("Withdrawal amount must be positive with no more than two decimal places.");
        }

        //Open one database connection for all three operations.
        try (Connection connection = connectionProvider.getConnection()) {
            connection.setAutoCommit(false);

            try {
                //Check ownership and available funds in the atomic database update.
                BigDecimal updatedBalance = accountDAO.withdraw(
                        connection, account.getId(), customer.getId(), amount);

                //Record the withdrawal using the same connection.
                long transactionId = transactionDAO.insertWithdrawalTransaction(
                        connection, account.getId(), amount, updatedBalance);

                //Record the successful withdrawal audit before committing.
                transactionDAO.insertWithdrawalAudit(connection, customer.getId(), transactionId);

                //Commit the balance, transaction, and audit together.
                connection.commit();
                return transactionId;
            } catch (SQLException | RuntimeException exception) {
                //Roll back all changes when any operation fails.
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }
                throw exception;
            }
        }
    }


    /**
     * Transfers money between two active Checking or Savings Accounts
     * belonging to the authenticated customer.
     * Both balance updates, the transaction record, and the audit are atomic.
     *
     * @param customer the authenticated customer making the transfer
     * @param sourceAccount the account sending the money
     * @param destinationAccount the account receiving the money
     * @param amount the amount being transferred
     * @return the transaction ID generated by PostgreSQL
     * @throws SQLException if any database operation fails
     */
    public long transfer(Customer customer, Account sourceAccount,
                         Account destinationAccount, BigDecimal amount) throws SQLException {
        //Require an active customer with a saved database ID.
        if (customer == null || customer.getId() <= 0 ||
                !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException("An active customer is required to make a transfer.");
        }

        //Require two different saved accounts.
        if (sourceAccount == null || destinationAccount == null ||
                sourceAccount.getId() <= 0 || destinationAccount.getId() <= 0 ||
                sourceAccount.getId() == destinationAccount.getId()) {
            throw new IllegalArgumentException("Two different valid accounts are required.");
        }

        //Only Checking and Savings Accounts can participate in regular transfers.
        if ((!"CHECKING".equals(sourceAccount.getAccountType()) &&
                !"SAVINGS".equals(sourceAccount.getAccountType())) ||
                (!"CHECKING".equals(destinationAccount.getAccountType()) &&
                        !"SAVINGS".equals(destinationAccount.getAccountType()))) {
            throw new IllegalArgumentException(
                    "Transfers are only available between Checking and Savings Accounts.");
        }

        //Both accounts must be active.
        if (!"ACTIVE".equals(sourceAccount.getStatus()) ||
                !"ACTIVE".equals(destinationAccount.getStatus())) {
            throw new IllegalStateException("Transfers require two active accounts.");
        }

        //Reject zero, negative, and fractional-cent amounts.
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException(
                    "Transfer amount must be positive with no more than two decimal places.");
        }

        //Use one connection for both balances, the transaction record, and the audit.
        try (Connection connection = connectionProvider.getConnection()) {
            connection.setAutoCommit(false);

            try {
                //Deduct the transfer amount from the source account.
                BigDecimal sourceBalanceAfter = accountDAO.debitTransfer(
                        connection, sourceAccount.getId(), customer.getId(), amount);

                //Credit the destination account using the same database transaction.
                BigDecimal destinationBalanceAfter = accountDAO.creditTransfer(
                        connection, destinationAccount.getId(), customer.getId(), amount);

                //Record both account IDs and their resulting balances.
                long transactionId = transactionDAO.insertTransferTransaction(
                        connection, sourceAccount.getId(), destinationAccount.getId(),
                        amount, sourceBalanceAfter, destinationBalanceAfter);

                //Save the audit before committing.
                transactionDAO.insertTransferAudit(connection, customer.getId(), transactionId);

                //Commit only after all four operations succeed.
                connection.commit();

                return transactionId;
            } catch (SQLException | RuntimeException exception) {
                //Undo both balance updates and records if any operation fails.
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }

                throw exception;
            }
        }
    }


    /**
     * Repays an active Loan Account using an active Checking or Savings Account
     * belonging to the authenticated customer.
     * Debits the funding account, reduces the outstanding loan balance,
     * records the transaction and audit, and commits all changes together.
     * A fully repaid Loan Account is automatically closed by AccountDAO.
     *
     * @param customer the authenticated customer making the repayment
     * @param sourceAccount the Checking or Savings Account funding the repayment
     * @param loanAccount the Loan Account receiving the repayment
     * @param amount the repayment amount
     * @return the transaction ID generated by PostgreSQL
     * @throws SQLException if any database operation fails
     */
    public long repayLoan(Customer customer, Account sourceAccount,
                          Account loanAccount, BigDecimal amount) throws SQLException {
        //Require an active customer with a valid database ID.
        if (customer == null || customer.getId() <= 0 || !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException("An active customer is required to repay a loan.");
        }

        //Require two different saved accounts.
        if (sourceAccount == null || loanAccount == null || sourceAccount.getId() <= 0 || loanAccount.getId() <= 0
                || sourceAccount.getId() == loanAccount.getId()) {
            throw new IllegalArgumentException("Two different valid accounts are required for loan repayment.");
        }

        //Only Checking and Savings Accounts can fund a loan repayment.
        if (!"CHECKING".equals(sourceAccount.getAccountType()) && !"SAVINGS".equals(sourceAccount.getAccountType())) {
            throw new IllegalArgumentException("Loan repayments must be funded by a Checking or Savings Account.");
        }

        //The destination must be a Loan Account.
        if (!"LOAN".equals(loanAccount.getAccountType())) {
            throw new IllegalArgumentException("Loan repayments must be sent to a Loan Account.");
        }

        //Both accounts must be active.
        if (!"ACTIVE".equals(sourceAccount.getStatus()) || !"ACTIVE".equals(loanAccount.getStatus())) {
            throw new IllegalStateException("Loan repayments require active accounts.");
        }

        //Reject zero, negative, and fractional-cent repayment amounts.
        if (amount == null || amount.signum() <= 0 || amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("Loan repayment amount must be positive with no more than two decimal places.");
        }

        //Require both selected accounts to belong to the authenticated customer.
        //The DAO methods also enforce ownership directly in PostgreSQL.
        if (sourceAccount.getAccountOwnerName() == null || loanAccount.getAccountOwnerName() == null ||
                sourceAccount.getAccountOwnerName().getId() != customer.getId() ||
                loanAccount.getAccountOwnerName().getId() != customer.getId()) {
            throw new IllegalArgumentException("Both accounts must belong to the authenticated customer.");
        }

        //Use one connection for both balance updates, the transaction, and the audit.
        try (Connection connection = connectionProvider.getConnection()) {
            connection.setAutoCommit(false);

            try {
                //Debit the customer's active Checking or Savings Account.
                BigDecimal sourceBalanceAfter = accountDAO.debitTransfer(connection, sourceAccount.getId(), customer.getId(), amount);

                //Reduce the outstanding loan balance.
                //AccountDAO automatically closes the loan when its balance reaches zero.
                BigDecimal loanBalanceAfter = accountDAO.repayLoan(connection, loanAccount.getId(), customer.getId(), amount);

                //Record both account IDs and their resulting balances.
                long transactionId = transactionDAO.insertLoanRepaymentTransaction(connection, sourceAccount.getId(),
                        loanAccount.getId(), amount, sourceBalanceAfter, loanBalanceAfter);

                //Record the successful repayment audit before committing.
                transactionDAO.insertLoanRepaymentAudit(connection, customer.getId(), transactionId);

                //Commit only after every database operation succeeds.
                connection.commit();

                return transactionId;
            }
            catch (SQLException | RuntimeException exception) {
                //Undo the funding debit, loan update, transaction, and audit.
                try {
                    connection.rollback();
                }
                catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }

                throw exception;
            }
        }
    }


    /**
     * Contributes money from an active Checking or Savings Account to an
     * active Investment Account belonging to the authenticated customer.
     * Debits the funding account, credits the Investment Account, records
     * the contribution date, transaction, and audit atomically.
     *
     * @param customer the authenticated customer making the contribution
     * @param sourceAccount the Checking or Savings Account providing funds
     * @param investmentAccount the Investment Account receiving the funds
     * @param amount the contribution amount
     * @return the banking transaction ID generated by PostgreSQL
     * @throws SQLException if any database operation fails
     */
    public long contributeToInvestment(Customer customer, Account sourceAccount,
                                       Account investmentAccount, BigDecimal amount)
            throws SQLException {
        //Require an active customer with a valid database ID.
        if (customer == null || customer.getId() <= 0 ||
                !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException(
                    "An active customer is required to contribute to an Investment Account.");
        }

        //Require two different saved accounts.
        if (sourceAccount == null || investmentAccount == null ||
                sourceAccount.getId() <= 0 || investmentAccount.getId() <= 0 ||
                sourceAccount.getId() == investmentAccount.getId()) {
            throw new IllegalArgumentException(
                    "Two different valid accounts are required for an investment contribution.");
        }

        //Only Checking and Savings Accounts can fund an investment.
        if (!"CHECKING".equals(sourceAccount.getAccountType()) &&
                !"SAVINGS".equals(sourceAccount.getAccountType())) {
            throw new IllegalArgumentException(
                    "Investment contributions must be funded by a Checking or Savings Account.");
        }

        //The receiving account must be an Investment Account.
        if (!"INVESTMENT".equals(investmentAccount.getAccountType())) {
            throw new IllegalArgumentException(
                    "Investment contributions must be sent to an Investment Account.");
        }

        //Both accounts must be active.
        if (!"ACTIVE".equals(sourceAccount.getStatus()) ||
                !"ACTIVE".equals(investmentAccount.getStatus())) {
            throw new IllegalStateException(
                    "Investment contributions require active accounts.");
        }

        //Reject zero, negative, fractional-cent, and oversized amounts.
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2 ||
                amount.setScale(2, java.math.RoundingMode.UNNECESSARY).precision() > 19) {
            throw new IllegalArgumentException(
                    "Investment contribution must be positive, within the monetary limit, and have no more than two decimal places.");
        }

        //Require both accounts to belong to the authenticated customer.
        //The DAO balance updates also enforce ownership in PostgreSQL.
        if (sourceAccount.getAccountOwnerName() == null ||
                investmentAccount.getAccountOwnerName() == null ||
                sourceAccount.getAccountOwnerName().getId() != customer.getId() ||
                investmentAccount.getAccountOwnerName().getId() != customer.getId()) {
            throw new IllegalArgumentException(
                    "Both accounts must belong to the authenticated customer.");
        }

        //Use one database connection for every contribution operation.
        try (Connection connection = connectionProvider.getConnection()) {
            connection.setAutoCommit(false);

            try {
                //Debit the customer's active Checking or Savings Account.
                BigDecimal sourceBalanceAfter = accountDAO.debitTransfer(
                        connection, sourceAccount.getId(), customer.getId(), amount);

                //Credit the active Investment Account before its unlock date.
                BigDecimal investmentBalanceAfter =
                        accountDAO.creditInvestmentContribution(
                                connection, investmentAccount.getId(),
                                customer.getId(), amount);

                //Record the contribution amount and PostgreSQL contribution date.
                accountDAO.insertInvestmentContribution(
                        connection, investmentAccount.getId(), amount);

                //Record the banking transaction and both updated balances.
                long transactionId =
                        transactionDAO.insertInvestmentContributionTransaction(
                                connection, sourceAccount.getId(),
                                investmentAccount.getId(), amount,
                                sourceBalanceAfter, investmentBalanceAfter);

                //Record the successful audit event.
                transactionDAO.insertInvestmentContributionAudit(
                        connection, customer.getId(), transactionId);

                //Commit only after all five database operations succeed.
                connection.commit();

                return transactionId;
            } catch (SQLException | RuntimeException exception) {
                //Undo both balance changes and all records if anything fails.
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }

                throw exception;
            }
        }
    }

    /**
     * Retrieves the transaction history for an account belonging
     * to the authenticated customer.
     *
     * @param customer the authenticated customer
     * @param account the selected bank account
     * @return the selected account's transaction history
     * @throws SQLException if the history cannot be retrieved
     */
    public List<TransactionHistoryEntry> getTransactionHistory(Customer customer, Account account) throws SQLException {

        //Require an authenticated customer with a valid database ID.
        if (customer == null || customer.getId() <= 0 ||
                !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException(
                    "An active customer is required to view transaction history.");
        }

        //Require an account that has been saved in PostgreSQL.
        if (account == null || account.getId() <= 0) {
            throw new IllegalArgumentException(
                    "A valid account is required to view transaction history.");
        }

        //Retrieve the history without starting a write transaction.
        try (Connection connection = connectionProvider.getConnection()) {
            return transactionDAO.getTransactionHistory(
                    connection, customer.getId(), account.getId());
        }
    }


    /**
     * Releases a matured investment and pays its contributions and earned interest
     * into the customer's active Checking or Savings Account in one transaction.
     *
     * @param customer the authenticated customer
     * @param investmentAccount the matured Investment Account
     * @param destinationAccount the Checking or Savings Account receiving the payout
     * @return the generated banking transaction ID
     * @throws SQLException if any payout operation fails
     */
    public long payMaturedInvestment(Customer customer, InvestmentAccount investmentAccount,
                                    Account destinationAccount) throws SQLException {
        //Reject invalid requests before opening a database connection.
        if (customer == null || customer.getId() <= 0 || !"ACTIVE".equals(customer.getStatus())) {
            throw new IllegalArgumentException("An active customer is required for a maturity payout.");
        }
        if (investmentAccount == null || destinationAccount == null ||
                investmentAccount.getId() <= 0 || destinationAccount.getId() <= 0 ||
                investmentAccount.getId() == destinationAccount.getId()) {
            throw new IllegalArgumentException("Two different saved accounts are required.");
        }
        if (!"CHECKING".equals(destinationAccount.getAccountType()) &&
                !"SAVINGS".equals(destinationAccount.getAccountType())) {
            throw new IllegalArgumentException("The payout destination must be Checking or Savings.");
        }
        if (!"ACTIVE".equals(destinationAccount.getStatus()) ||
                !InvestmentMaturityValidator.isEligibleForMaturityPayout(investmentAccount, LocalDate.now())) {
            throw new IllegalStateException("The destination must be active and the investment matured.");
        }
        if (investmentAccount.getAccountOwnerName() == null ||
                destinationAccount.getAccountOwnerName() == null ||
                investmentAccount.getAccountOwnerName().getId() != customer.getId() ||
                destinationAccount.getAccountOwnerName().getId() != customer.getId()) {
            throw new IllegalArgumentException("Both accounts must belong to the customer.");
        }

        //Release first to lock the investment against concurrent contributions or payouts.
        try (Connection connection = connectionProvider.getConnection()) {
            connection.setAutoCommit(false);
            try {
                BigDecimal contributions = accountDAO.releaseMaturedInvestment(
                        connection, investmentAccount.getId(), customer.getId());
                BigDecimal interest = new InvestmentInterestService(accountDAO)
                        .calculateTotalInterest(connection, investmentAccount);
                BigDecimal payout = contributions.add(interest);

                //An unfunded investment cannot produce a positive payout transaction.
                if (payout.signum() <= 0 || payout.stripTrailingZeros().scale() > 2 ||
                        payout.setScale(2, java.math.RoundingMode.UNNECESSARY).precision() > 19) {
                    throw new SQLException("The investment maturity payout amount is invalid.");
                }

                BigDecimal destinationBalance = accountDAO.creditInvestmentMaturityPayout(
                        connection, destinationAccount.getId(), customer.getId(), payout);
                long transactionId = transactionDAO.insertInvestmentMaturityTransaction(
                        connection, investmentAccount.getId(), destinationAccount.getId(),
                        payout, destinationBalance);
                transactionDAO.insertInvestmentMaturityAudit(connection, customer.getId(), transactionId);
                connection.commit();
                return transactionId;
            } catch (SQLException | RuntimeException exception) {
                //Restore the investment, destination, and records on any failure.
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }
                throw exception;
            }
        }
    }

}
