    /**
     * Records a successful deposit using an existing database transaction.
     *
     * @param connection the connection managing the transaction
     * @param accountId the receiving account's database ID
     * @param amount the deposited amount
     * @param updatedBalance the account balance after the deposit
     * @return the transaction ID generated by PostgreSQL
     * @throws SQLException if the transaction record cannot be saved
     */
    public long insertDepositTransaction(Connection connection, long accountId,
                                         BigDecimal amount, BigDecimal updatedBalance) throws SQLException {
        //Check that the account ID and financial values are valid.
        if (accountId <= 0) {
            throw new IllegalArgumentException("A valid account ID is required.");
        }
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("A valid deposit amount is required.");
        }
        if (updatedBalance == null || updatedBalance.signum() < 0 ||
                updatedBalance.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("A valid updated balance is required.");
        }

        //Generate a unique reference number for this deposit.
        //PostgreSQL now generates the transaction ID instead of a Java UUID.

        String sqlQuery = """
            INSERT INTO transactions
                (source_account_id, destination_account_id,
                 transaction_type, amount, status, description,
                 source_balance_after, destination_balance_after)
            VALUES (NULL, ?, 'DEPOSIT', ?, 'SUCCESS', ?, NULL, ?)
            RETURNING transaction_id
            """;

        //Use the caller's connection so this record and the balance update stay atomic.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setLong(1, accountId);
            preparedStatement.setBigDecimal(2, amount);
            preparedStatement.setString(3, "Cash deposit");
            preparedStatement.setBigDecimal(4, updatedBalance);

            //Require exactly one transaction record to be inserted.
            //Read the generated ID returned by PostgreSQL.
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Deposit transaction record was not saved correctly.");
                }
                long transactionId = resultSet.getLong("transaction_id");
                if (transactionId <= 0) {
                    throw new SQLException("PostgreSQL returned an invalid transaction ID.");
                }
                return transactionId;
            }
        }
    }


