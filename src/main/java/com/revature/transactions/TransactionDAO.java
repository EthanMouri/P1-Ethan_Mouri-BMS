    /**
     * Records a successful transfer between two bank accounts.
     *
     * @param connection the connection managing the transfer
     * @param sourceAccountId the account sending the money
     * @param destinationAccountId the account receiving the money
     * @param amount the transferred amount
     * @param sourceBalanceAfter the source balance after the transfer
     * @param destinationBalanceAfter the destination balance after the transfer
     * @return the transaction ID generated by PostgreSQL
     * @throws SQLException if the transaction record cannot be saved
     */
    public long insertTransferTransaction(Connection connection, long sourceAccountId,
                                          long destinationAccountId, BigDecimal amount,
                                          BigDecimal sourceBalanceAfter,
                                          BigDecimal destinationBalanceAfter) throws SQLException {
        //Check that both account IDs are valid and different.
        if (sourceAccountId <= 0 || destinationAccountId <= 0 ||
                sourceAccountId == destinationAccountId) {
            throw new IllegalArgumentException("Two different valid accounts are required.");
        }

        //Check that the amount is valid.
        if (amount == null || amount.signum() <= 0 ||
                amount.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("A valid transfer amount is required.");
        }

        //Check that both updated balances are valid.
        if (sourceBalanceAfter == null || sourceBalanceAfter.signum() < 0 ||
                sourceBalanceAfter.stripTrailingZeros().scale() > 2 ||
                destinationBalanceAfter == null || destinationBalanceAfter.signum() < 0 ||
                destinationBalanceAfter.stripTrailingZeros().scale() > 2) {
            throw new IllegalArgumentException("Valid updated account balances are required.");
        }

        String sqlQuery = """
            INSERT INTO transactions
                (source_account_id, destination_account_id,
                 transaction_type, amount, status, description,
                 source_balance_after, destination_balance_after)
            VALUES (?, ?, 'TRANSFER', ?, 'SUCCESS', ?, ?, ?)
            RETURNING transaction_id
            """;

        //Save the transfer using the same connection as both balance updates.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setLong(1, sourceAccountId);
            preparedStatement.setLong(2, destinationAccountId);
            preparedStatement.setBigDecimal(3, amount);
            preparedStatement.setString(4, "Transfer between own accounts");
            preparedStatement.setBigDecimal(5, sourceBalanceAfter);
            preparedStatement.setBigDecimal(6, destinationBalanceAfter);

            //Read the transaction ID returned by PostgreSQL.
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                if (!resultSet.next()) {
                    throw new SQLException("Transfer transaction record was not saved correctly.");
                }

                long transactionId = resultSet.getLong("transaction_id");
                if (transactionId <= 0) {
                    throw new SQLException("PostgreSQL returned an invalid transaction ID.");
                }

                return transactionId;
            }
        }
    }

