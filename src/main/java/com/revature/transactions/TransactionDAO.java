    /**
     * Retrieves transaction history for an account owned by the customer.
     * Includes transactions where the account is either the source or destination.
     *
     * @param connection the database connection used for the query
     * @param customerId the authenticated customer's database ID
     * @param accountId the selected account's database ID
     * @return transaction history ordered from newest to oldest
     * @throws SQLException if the database query fails
     */
    public List<TransactionHistoryEntry> getTransactionHistory(
            Connection connection, long customerId, long accountId) throws SQLException {

        //Reject invalid customer and account IDs before querying PostgreSQL.
        if (customerId <= 0 || accountId <= 0) {
            throw new IllegalArgumentException("Valid customer and account IDs are required.");
        }

        String sqlQuery = """
            SELECT
                t.transaction_id, t.transaction_type, t.amount, t.status, t.description, t.created_at,
                CASE
                    WHEN t.destination_account_id = ? THEN 'IN'
                    ELSE 'OUT'
                END AS direction,
                CASE
                    WHEN t.destination_account_id = ? THEN t.destination_balance_after
                    ELSE t.source_balance_after
                END AS balance_after
            FROM transactions t
            INNER JOIN accounts a
                ON a.account_id = ?
                AND a.customer_id = ?
            WHERE t.source_account_id = a.account_id
               OR t.destination_account_id = a.account_id
            ORDER BY t.created_at DESC, t.transaction_id DESC
            """;

        List<TransactionHistoryEntry> history = new ArrayList<>();

        //Use the supplied connection without changing or committing anything.
        try (PreparedStatement preparedStatement = connection.prepareStatement(sqlQuery)) {
            preparedStatement.setLong(1, accountId);
            preparedStatement.setLong(2, accountId);
            preparedStatement.setLong(3, accountId);
            preparedStatement.setLong(4, customerId);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                while (resultSet.next()) {
                    //Read the transaction from the selected account's perspective.
                    history.add(new TransactionHistoryEntry(
                            resultSet.getLong("transaction_id"),
                            resultSet.getString("transaction_type"),
                            resultSet.getBigDecimal("amount"),
                            resultSet.getString("direction"),
                            resultSet.getString("status"),
                            resultSet.getString("description"),
                            resultSet.getBigDecimal("balance_after"),
                            resultSet.getObject("created_at", OffsetDateTime.class)
                    ));
                }
            }
        }

        return history;
    }



